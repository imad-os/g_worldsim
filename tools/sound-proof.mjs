// Browser proof of the sounds: the manifest loads, one-shots decode after the first button press, footsteps / hits / menu
// sounds play, ambience loops fade in, the Sound settings page. Usage: ADMIN_TOKEN=... node tools/sound-proof.mjs <server> <sdk.js> <outdir>
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
import WebSocket from 'ws';
import { encode, decode } from '@msgpack/msgpack';
const [server, sdkPath, out] = process.argv.slice(2);
const fs = await import('node:fs');
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
await page.route(/mypc-sdk\.js/, (r) => r.fulfill({ contentType: 'text/javascript', body: fs.readFileSync(sdkPath) }));
const ws = new WebSocket(server.replace(/^http/, 'ws') + '/ws');
await new Promise((r) => ws.on('open', r));
ws.send(encode({ t: 'hi', v: 1, token: process.env.ADMIN_TOKEN, name: 'proof' }));
const answers = new Map();
ws.on('message', (d) => { const m = decode(d); if (m.t === 'admr') answers.set(m.id, m); });
let aid = 100;
const adm = async (c) => { const id = ++aid; ws.send(encode({ t: 'adm', id, c })); for (let k = 0; k < 50 && !answers.has(id); k++) await new Promise((r) => setTimeout(r, 100)); return answers.get(id); };
await page.goto(`${server}/app/?server=${encodeURIComponent(server)}&tier=low&dev`);
await page.waitForFunction(() => document.getElementById('screen').hidden, null, { timeout: 40000 });
await page.waitForTimeout(5000);
const snd = () => page.evaluate(() => window.__dev.snd());
const menu = () => page.evaluate(() => document.getElementById('gmenu')?.hidden === false ? [...document.querySelectorAll('#gmenu .mt, #gmenu .mr')].map((e) => (e.classList.contains('on') ? '>' : '') + e.textContent).join(' | ') : '');
const key = async (k, n = 1) => { for (let i = 0; i < n; i++) { await page.keyboard.press(k); await page.waitForTimeout(220); } };
const goRow = async (label) => { for (let k = 0; k < 30; k++) { if ((await menu()).includes('>' + label)) return; await key('ArrowDown'); } throw new Error('row not found ' + label); };
console.log('1 before any button:', JSON.stringify(await snd()));
if ((await menu()).includes('How I look')) { await goRow('Save'); await key('Enter'); await page.waitForTimeout(600); if (await menu()) await key('Escape'); await page.waitForTimeout(400); }
console.log('1b menu:', await menu() || '(closed)', '| at', JSON.stringify(await page.evaluate(() => window.__dev.me())));
await page.keyboard.down('ArrowRight'); await page.waitForTimeout(2500); await page.keyboard.up('ArrowRight');
await page.waitForTimeout(2500);
await page.keyboard.down('ArrowDown'); await page.waitForTimeout(2000); await page.keyboard.up('ArrowDown');
const s2 = await snd();
console.log('2 at', JSON.stringify(await page.evaluate(() => window.__dev.me())));
console.log('2 after walking:', JSON.stringify({ ...s2, log: s2.log.join(' ') }));
const [mx, my, map] = await page.evaluate(() => window.__dev.me());
await adm({ cmd: 'zombieSpawn', map, x: mx + 1.6, y: my, stays: true });
await page.waitForTimeout(1200);
await page.evaluate(() => window.__dev.act('attack')); await page.waitForTimeout(800);
await page.evaluate(() => window.__dev.act('attack')); await page.waitForTimeout(800);
await page.evaluate(() => window.__dev.act('menu')); await page.waitForTimeout(300);
await goRow('Settings'); await key('Enter'); await goRow('Sound'); await key('Enter'); await page.waitForTimeout(300);
console.log('3 sound page:', await menu());
await goRow('Ambience'); await key('Enter'); await page.waitForTimeout(300);
console.log('3 after OK on ambience:', (await menu()).split(' | ').find((r) => r.includes('Ambience')));
await page.screenshot({ path: `${out}/7-sound-settings.png` });
await page.waitForTimeout(3000);
const s3 = await snd();
console.log('4 sounds played:', s3.log.join(' '), '| loops:', s3.loops.join(' '), '| decoded', s3.decoded, 'of', s3.sounds, '| state', s3.state);
await browser.close(); ws.close();
